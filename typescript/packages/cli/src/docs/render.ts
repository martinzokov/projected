import type { Access, AnyContracts, AnyOperationContract } from "@projected/application";
import type { CodeModel, Usage } from "./analyze.js";

const id = (prefix: string, name: string) => `${prefix}_${name.replace(/[^A-Za-z0-9]/g, "_")}`;
const quote = (text: string) => `"${text.replace(/"/g, "#quot;")}"`;
const cell = (values: readonly string[]) => (values.length === 0 ? "—" : values.map((value) => value.replace(/\|/g, "\\|")).join(", "));
const code = (values: readonly string[]) => cell(values.map((value) => `\`${value}\``));
const label = (contract: AnyOperationContract) => `${contract.type} v${contract.version}`;

function accessText(access: Access): string {
  if (access === "public") return "public";
  if (access === "authenticated") return "authenticated";
  return `permissions: ${access.permissions.join(", ")}`;
}

const NONE: Usage = { writes: [], reads: [], emits: [], ports: [], remotes: [] };

/**
 * The catalog of one service: what it offers, what it stores, what it announces, what reacts,
 * and what it depends on — derived from its contracts and its code, as markdown with a Mermaid
 * flow diagram GitHub renders in place.
 */
export function renderCatalog(contracts: AnyContracts, model: CodeModel, flavour: string): string {
  const operations = [...contracts.commands, ...contracts.queries] as AnyOperationContract[];
  const handlerOf = (contract: AnyOperationContract) => model.bindings[contract.key];
  const usageOf = (contract: AnyOperationContract): Usage => model.useCases.find((u) => u.name === handlerOf(contract)) ?? NONE;

  const lines: string[] = [
    `# ${contracts.name} — service catalog`,
    "",
    "> Generated by `projected docs` from the code. Do not edit: run `projected docs` after changing the",
    "> service — `projected check` fails while this file is out of date.",
    "",
    [contracts.description, `Flavour: **${flavour}**.`].filter((part) => part !== undefined && part !== "").join(" "),
    "",
    "## How it fits together",
    "",
    "Commands (rectangles) write aggregates (hexagons), which record events (flags); event handlers",
    "(double boxes) react to them through ports (cylinders). Queries (rounded) read, along dotted lines.",
    "Circles are broker topics, parallelograms other services.",
    "",
    "```mermaid",
    "flowchart LR",
  ];

  const nodes = new Map<string, string>();
  const edges = new Set<string>();
  const node = (key: string, shape: string) => nodes.set(key, `  ${key}${shape}`);
  for (const contract of operations) {
    const key = id("op", contract.key);
    const text = quote(`${label(contract)}${contract.deprecated ? " (deprecated)" : ""}`);
    node(key, contract.kind === "command" ? `[${text}]` : `(${text})`);
    const usage = usageOf(contract);
    for (const aggregate of usage.writes) edges.add(`  ${key} --> ${id("agg", aggregate)}`);
    for (const aggregate of usage.reads) edges.add(`  ${key} -.-> ${id("agg", aggregate)}`);
    for (const port of usage.ports) edges.add(`  ${key} ${contract.kind === "query" ? "-.->" : "-->"} ${id("port", port)}`);
    for (const remote of usage.remotes) edges.add(`  ${key} --> ${id("remote", remote)}`);
  }
  for (const aggregate of model.aggregates) {
    node(id("agg", aggregate.name), `{{${quote(aggregate.name)}}}`);
    for (const event of aggregate.events) edges.add(`  ${id("agg", aggregate.name)} --> ${id("evt", event)}`);
    for (const topic of model.relays) edges.add(`  ${id("agg", aggregate.name)} -.->|relayed| ${id("topic", topic)}`);
  }
  for (const event of model.events) node(id("evt", event.type), `>${quote(event.type)}]`);
  for (const handler of model.eventHandlers) {
    node(id("eh", handler.name), `[[${quote(handler.name)}]]`);
    for (const event of handler.consumes) edges.add(`  ${id("evt", event)} --> ${id("eh", handler.name)}`);
    for (const port of handler.ports) edges.add(`  ${id("eh", handler.name)} --> ${id("port", port)}`);
    for (const aggregate of handler.writes) edges.add(`  ${id("eh", handler.name)} --> ${id("agg", aggregate)}`);
    for (const remote of handler.remotes) edges.add(`  ${id("eh", handler.name)} --> ${id("remote", remote)}`);
  }
  for (const port of model.ports) node(id("port", port.name), `[(${quote(port.name)})]`);
  for (const topic of model.relays) node(id("topic", topic), `((${quote(topic)}))`);
  const remotes = [...new Set([...model.useCases, ...model.eventHandlers].flatMap((unit) => unit.remotes))].sort();
  for (const remote of remotes) node(id("remote", remote), `[/${quote(remote)}/]`);
  lines.push(...[...nodes.values()], ...[...edges].sort(), "```", "");

  lines.push(
    "## Operations",
    "",
    "Served over HTTP (`POST /commands|queries/{type}/version/{n}`), in batches and from a message queue.",
    "",
    "| Operation | Kind | Access | Business errors | Handler | Writes | Reads | Emits | Ports |",
    "|---|---|---|---|---|---|---|---|---|",
  );
  for (const contract of operations) {
    const usage = usageOf(contract);
    const name = `\`${contract.type}\` v${contract.version}${contract.deprecated ? " *(deprecated)*" : ""}`;
    const handler = handlerOf(contract);
    lines.push(
      `| ${name} | ${contract.kind} | ${accessText(contracts.accessOf(contract))} | ${code(contract.errors.map((e) => e.tag))} | ${handler === undefined ? "—" : `\`${handler}\``} | ${cell(usage.writes)} | ${cell(usage.reads)} | ${code(usage.emits)} | ${code(usage.ports)} |`,
    );
  }

  const byAggregate = (pick: (usage: Usage) => readonly string[], aggregate: string) =>
    operations.filter((contract) => pick(usageOf(contract)).includes(aggregate)).map(label);
  if (model.aggregates.length > 0) {
    lines.push("", "## Aggregates", "", "| Aggregate | Events | Written by | Read by | Defined in |", "|---|---|---|---|---|");
    for (const aggregate of model.aggregates) {
      lines.push(
        `| \`${aggregate.name}\` | ${code(aggregate.events)} | ${cell(byAggregate((u) => u.writes, aggregate.name))} | ${cell(byAggregate((u) => u.reads, aggregate.name))} | \`${aggregate.file}\` |`,
      );
    }
  }

  if (model.events.length > 0) {
    lines.push("", "## Events", "", "| Event | Version | Aggregate | Emitted by | Consumed by |", "|---|---|---|---|---|");
    for (const event of model.events) {
      const aggregate = model.aggregates.filter((a) => a.events.includes(event.type)).map((a) => a.name);
      const emitters = [
        ...operations.filter((contract) => usageOf(contract).emits.includes(event.type)).map(label),
        ...model.eventHandlers.filter((h) => h.emits.includes(event.type)).map((h) => h.name),
      ];
      const consumers = [...model.eventHandlers.filter((h) => h.consumes.includes(event.type)).map((h) => h.name), ...model.relays.map((t) => `relay → ${t}`)];
      lines.push(`| \`${event.type}\` | ${event.version} | ${cell(aggregate)} | ${cell(emitters)} | ${cell(consumers)} |`);
    }
  }

  if (model.eventHandlers.length > 0) {
    lines.push("", "## Event handlers", "", "| Handler | Consumes | Ports | Writes | Emits | Defined in |", "|---|---|---|---|---|---|");
    for (const handler of model.eventHandlers) {
      lines.push(
        `| \`${handler.name}\` | ${code(handler.consumes)} | ${code(handler.ports)} | ${cell(handler.writes)} | ${code(handler.emits)} | \`${handler.file}\` |`,
      );
    }
  }

  if (model.ports.length > 0) {
    lines.push("", "## Driven ports", "", "| Port | Operations | Adapters | Used by |", "|---|---|---|---|");
    for (const port of model.ports) {
      const users = [
        ...operations.filter((contract) => usageOf(contract).ports.includes(port.name)).map(label),
        ...model.eventHandlers.filter((h) => h.ports.includes(port.name)).map((h) => h.name),
      ];
      lines.push(`| \`${port.name}\` | ${code(port.operations)} | ${code(port.adapters)} | ${cell(users)} |`);
    }
  }

  if (model.relays.length > 0 || remotes.length > 0) {
    lines.push("", "## Outside the service", "");
    for (const topic of model.relays) lines.push(`- Every event is relayed to the \`${topic}\` topic.`);
    for (const remote of remotes) lines.push(`- Calls the \`${remote}\` service.`);
  }
  return `${lines.join("\n")}\n`;
}
